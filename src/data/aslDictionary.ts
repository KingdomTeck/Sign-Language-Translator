export function findMatchingASLCue(text: string): ASLSignItem | undefined {
  if (!text) return undefined;
  const clean = text.toLowerCase();

  return ASL_DICTIONARY.find((item) => {
    const nameMatch = clean.includes(item.name.toLowerCase());
    const idMatch = clean.includes(item.id.replace('_', ' '));
    const equivMatch = clean.includes(item.spokenEquivalent.toLowerCase().slice(0, 10));
    return nameMatch || idMatch || equivMatch;
  });
}
